from typing import Tuple, Optional, Set, List, Dict, Any
from app.graph.state import ExecutionPlan, Task


REGISTERED_WORKERS: Set[str] = {
    "rag",
    "research",
    "tutor",
    "mcq",
    "flashcard",
    "direct_answer",
}

DEFAULT_MAX_TASKS = 10


class PlanValidator:
    """
    Dedicated deterministic validator for ExecutionPlans generated by the Planner Agent.
    Enforces strict DAG topology, registered worker validation, and sanity limits.
    Does not execute tools or use LLM inference.
    """

    def __init__(
        self,
        registered_workers: Optional[Set[str]] = None,
        max_tasks: int = DEFAULT_MAX_TASKS,
    ):
        self.registered_workers = registered_workers or REGISTERED_WORKERS
        self.max_tasks = max_tasks

    def validate(self, plan: ExecutionPlan) -> Tuple[bool, Optional[str]]:
        """
        Validates an ExecutionPlan.
        Returns:
            (is_valid: bool, error_message: Optional[str])
        """
        if not plan:
            return False, "Plan is empty or None."

        if not plan.tasks:
            if plan.is_direct:
                return True, None
            return False, "Plan contains no tasks and is not marked as direct."

        if len(plan.tasks) > self.max_tasks:
            return False, f"Task count ({len(plan.tasks)}) exceeds maximum limit of {self.max_tasks}."

        task_ids: Set[str] = set()
        task_map: Dict[str, Task] = {}

        # 1. Validate unique IDs and worker registration
        for task in plan.tasks:
            if not task.task_id or not task.task_id.strip():
                return False, "Task found with missing or blank task_id."

            if task.task_id in task_ids:
                return False, f"Duplicate task_id detected: '{task.task_id}'."

            task_ids.add(task.task_id)
            task_map[task.task_id] = task

            if task.worker not in self.registered_workers:
                return (
                    False,
                    f"Task '{task.task_id}' references unregistered worker '{task.worker}'. "
                    f"Registered workers: {sorted(list(self.registered_workers))}.",
                )

            if not isinstance(task.input_mapping, dict):
                return False, f"Task '{task.task_id}' input_mapping must be a dictionary."

        # 2. Validate dependencies exist and no self-dependency
        for task in plan.tasks:
            for dep_id in task.dependencies:
                if dep_id == task.task_id:
                    return False, f"Self-dependency detected: Task '{task.task_id}' depends on itself."

                if dep_id not in task_ids:
                    return (
                        False,
                        f"Task '{task.task_id}' references non-existent dependency '{dep_id}'.",
                    )

        # 3. Detect cycles using Kahn's algorithm (Topological sort)
        in_degree: Dict[str, int] = {tid: 0 for tid in task_ids}
        adj_list: Dict[str, List[str]] = {tid: [] for tid in task_ids}

        for task in plan.tasks:
            in_degree[task.task_id] = len(task.dependencies)
            for dep in task.dependencies:
                adj_list[dep].append(task.task_id)

        # Queue nodes with in-degree 0 (no dependencies)
        queue = [tid for tid, deg in in_degree.items() if deg == 0]
        processed_count = 0

        while queue:
            current = queue.pop(0)
            processed_count += 1
            for neighbor in adj_list[current]:
                in_degree[neighbor] -= 1
                if in_degree[neighbor] == 0:
                    queue.append(neighbor)

        if processed_count != len(task_ids):
            return (
                False,
                "Cyclic dependency detected: The execution plan does not form a valid Directed Acyclic Graph (DAG).",
            )

        return True, None
